class Command(BaseCommand):
    help = 'Seeds initial starter food database with common estimated nutritional values (idempotent)'

    def handle(self, *args, **options):
        count_created = 0
        count_updated = 0
        for item in STARTER_FOODS:
            obj, created = FoodItem.objects.update_or_create(
                name=item['name'],
                defaults=item
            )
            if created:
                count_created += 1
            else:
                count_updated += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"Starter food database initialized. Created: {count_created}, Updated/Verified: {count_updated}."
            )
        )
